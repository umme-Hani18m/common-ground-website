create or replace view problem_summary as
select
  p.*,
  latest.id as solution_id,
  latest.description as solution,
  coalesce(v.vote_count, 0) as vote_count
from problems p
left join lateral (
  select s.id, s.description
  from solutions s
  where s.problem_id = p.id
  order by s.created_at desc
  limit 1
) latest on true
left join lateral (
  select count(*)::int as vote_count
  from votes v
  where v.problem_id = p.id and v.value = 1
) v on true;
